def validate_config():
    """Проверка корректности конфигурации"""
    assert DIM > 0, "Размерность должна быть положительной"
    assert NODES > 0, "Количество узлов должно быть положительным"
    assert E_0 > 0, "Энергия E_0 должна быть положительной"
    assert T_CONST > 0, "Температурная константа должна быть положительной"
    assert A_T > 0, "Параметр a_t должен быть положительным"


def get_element_symbol(z_number):
    """Получить символ элемента по атомному номеру"""
    return NUCLEAR_LIBRARY.get(int(z_number), f"Z{z_number}")


def initialize_mass_constants(delta_m_n, delta_m_p, delta_m_alpha):
    """Инициализация массовых констант после загрузки данных"""
    global DELTA_M_N, DELTA_M_P, DELTA_M_ALPHA, DELTA_M_N_GAMMA
    DELTA_M_N = delta_m_n
    DELTA_M_P = delta_m_p
    DELTA_M_ALPHA = delta_m_alpha
    DELTA_M_N_GAMMA = delta_m_n + E_GAMMA_THRES


